--> The item prices. Saidoro's "Sane Magic Item Prices" (shared for use with
--> credit to the author) prices each item on its own; its five price tables
--> are taken as the 5etools homebrew repository holds them. The magic items of
--> the SRD 5.2 (CC BY 4.0) the guide has no price for get the SRD's value for
--> their rarity, halved for a consumable. They belong to the instance, not to
--> a campaign, so a fresh instance has them without a seed. The search index
--> holds each item once, with no campaign; every campaign's search finds it.
CREATE TABLE `item_prices` (
	`id` text PRIMARY KEY NOT NULL,
	`name` text NOT NULL,
	`price_gp` integer NOT NULL,
	`list` text,
	`rarity` text,
	`source` text NOT NULL,
	`note` text DEFAULT '' NOT NULL,
	`rev` integer DEFAULT 1 NOT NULL,
	CONSTRAINT "item_prices_list_check" CHECK(`list` is null or `list` in ('consumable', 'combat', 'noncombat', 'summoning', 'gamechanging')),
	CONSTRAINT "item_prices_rarity_check" CHECK(`rarity` is null or `rarity` in ('common', 'uncommon', 'rare', 'very-rare', 'legendary')),
	CONSTRAINT "item_prices_source_check" CHECK(`source` in ('saidoro', 'srd')),
	CONSTRAINT "item_prices_source_fields_check" CHECK((`source` = 'saidoro' and `list` is not null and `rarity` is null) or (`source` = 'srd' and `rarity` is not null and `list` is null))
);
